import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import prettier from 'prettier'

const directory = path.dirname(fileURLToPath(import.meta.url))
const sourceRoot = path.resolve(directory, '../functions')
const { imports } = JSON.parse(
  await fs.readFile(path.join(sourceRoot, 'deno.json'), 'utf8'),
)
const formatting = await prettier.resolveConfig(directory)
const checking = process.argv.includes('--check')
const diagnostic = process.argv.includes('--diagnostic')

for (const name of diagnostic
  ? ['assessment-questions']
  : ['assessment-questions', 'submit-assessment']) {
  const seen = new Set()
  const external = new Set()
  const pieces = []

  async function inline(file) {
    if (seen.has(file)) return
    if (!file.startsWith(sourceRoot + path.sep)) {
      throw new Error('Import outside the Edge Function source directory')
    }
    seen.add(file)
    const source = await fs.readFile(file, 'utf8')
    const parsed = ts.createSourceFile(
      file,
      source,
      ts.ScriptTarget.Latest,
      true,
    )
    const removals = []
    for (const statement of parsed.statements) {
      if (!ts.isImportDeclaration(statement)) continue
      const specifier = statement.moduleSpecifier.text
      if (specifier.startsWith('.')) {
        await inline(path.resolve(path.dirname(file), specifier))
      } else {
        if (specifier !== '@supabase/supabase-js') {
          throw new Error(`Unexpected external import: ${specifier}`)
        }
        const resolved = imports[specifier]
        if (!/^npm:@supabase\/supabase-js@\d+\.\d+\.\d+$/.test(resolved)) {
          throw new Error('Expected an exact Supabase SDK version')
        }
        external.add(`import { createClient } from '${resolved}'`)
      }
      removals.push([statement.getStart(parsed), statement.getEnd()])
    }
    let body = source
    for (const [start, end] of removals.reverse()) {
      body = body.slice(0, start) + body.slice(end)
    }
    pieces.push(
      `// Inlined from ${path.relative(sourceRoot, file).replaceAll('\\', '/')}.\n${body.trim()}`,
    )
  }

  await inline(path.join(sourceRoot, name, 'index.ts'))
  if (diagnostic) {
    const entry = pieces.pop()
    if (!entry.includes('createQuestionsHandler(createDependencies)')) {
      throw new Error(
        'Unexpected questions entrypoint; diagnostic build aborted',
      )
    }
    pieces.push(
      await fs.readFile(
        path.join(directory, 'diagnostics.fragment.txt'),
        'utf8',
      ),
      entry.replace(
        'createQuestionsHandler(createDependencies)',
        'createQuestionsHandler(createDiagnosticDependencies)',
      ),
    )
  }
  const outputName = `${name}${diagnostic ? '-diagnostic' : ''}.ts`
  const output = await prettier.format(
    [
      `// Generated by node supabase/dashboard/build.mjs — do not edit manually.`,
      `// Paste this ENTIRE file into index.ts for the ${name} Dashboard function.`,
      '// Keep JWT verification enabled. All local shared modules are included below.',
      ...external,
      ...pieces,
      '',
    ].join('\n\n'),
    { ...formatting, parser: 'typescript' },
  )
  const target = path.join(directory, outputName)
  if (checking) {
    if (
      (await fs.readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== output
    ) {
      throw new Error(`${outputName} is stale; regenerate the Dashboard files`)
    }
  } else {
    await fs.writeFile(target, output)
  }
  console.log(`${checking ? 'Verified' : 'Generated'} ${outputName}`)
}
